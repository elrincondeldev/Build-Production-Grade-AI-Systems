"""Build the markdown cost report: API vs self-hosted, plus platform fixed costs."""

from __future__ import annotations

import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from kestrel_platform.capacity import (
    ApiPricing,
    CapacityInputs,
    api_monthly_cost,
    breakeven_requests_per_month,
    plan_capacity,
    self_host_monthly_cost,
)


@dataclass(frozen=True)
class OptionCost:
    label: str
    llm_month: float
    platform_month: float
    kind: str  # api | self_host

    @property
    def total(self) -> float:
        return self.llm_month + self.platform_month


def load_assumptions(path: Path) -> dict[str, Any]:
    return tomllib.loads(path.read_text())


def _inputs(a: dict[str, Any], scale: float = 1.0) -> CapacityInputs:
    t, s = a["traffic"], a["self_host"]
    return CapacityInputs(
        peak_rps=t["peak_rps"] * scale,
        avg_rps=t["avg_rps"] * scale,
        input_tokens=t["input_tokens"],
        output_tokens=t["output_tokens"],
        prefill_tokens_per_s=s["prefill_tokens_per_s"],
        decode_tokens_per_s=s["decode_tokens_per_s"],
        target_utilization=s["target_utilization"],
        min_replicas=s["min_replicas"],
        gpu_hourly_cost=s["gpu_hourly_cost"],
    )


def compute_options(a: dict[str, Any], scale: float = 1.0) -> list[OptionCost]:
    p = a["platform"]
    platform = p["fraud_service_pods"] * p["cpu_pod_month"] + p["vector_db_month"] + p["observability_month"]
    inputs = _inputs(a, scale)
    plan = plan_capacity(inputs)
    options = []
    for key in ("small", "large"):
        api = a["api"][key]
        cost = api_monthly_cost(
            plan.requests_per_month, inputs.input_tokens, inputs.output_tokens,
            ApiPricing(api["input_per_million"], api["output_per_million"]),
        )
        options.append(OptionCost(api["label"], cost, platform, "api"))
    options.append(
        OptionCost(a["self_host"]["label"], self_host_monthly_cost(plan, a["self_host"]["ops_overhead_per_month"]), platform, "self_host")
    )
    return options


def build_report(a: dict[str, Any]) -> str:
    inputs = _inputs(a)
    plan = plan_capacity(inputs)
    base = compute_options(a)
    grown = compute_options(a, a["traffic"]["growth_factor"])
    budget = a["budget"]
    lines = [
        "# Kestrel platform monthly cost report",
        "",
        "> Generated by `scripts/cost_report.py` from `cost_assumptions.toml`. All prices are illustrative placeholders; "
        "replace them with current provider pricing and your own load-test throughput.",
        "",
        "## Assumptions",
        "",
        f"- Traffic: {inputs.avg_rps} req/s average, {inputs.peak_rps} req/s peak → **{plan.requests_per_month:,.0f} requests/month**",
        f"- Tokens per request: {inputs.input_tokens} in, {inputs.output_tokens} out",
        f"- Self-hosting: {plan.gpu_seconds_per_request:.3f} GPU-s per request → {plan.replicas_at_avg} replicas on average, "
        f"{plan.replicas_at_peak} at peak (target utilisation {inputs.target_utilization:.0%}, min {inputs.min_replicas})",
        "",
        "## Monthly cost by option",
        "",
        "| Option | LLM | Platform (fraud-service, vector DB, observability) | **Total** | Cost / 1k requests | Within Q4 budget? |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for o in base:
        limit = budget["llm_api_month"] if o.kind == "api" else budget["gpu_month"]
        ok = "✅" if o.llm_month <= limit else "❌"
        per_1k = o.total / plan.requests_per_month * 1000
        lines.append(f"| {o.label} | €{o.llm_month:,.0f} | €{o.platform_month:,.0f} | **€{o.total:,.0f}** | €{per_1k:.3f} | {ok} (limit €{limit:,.0f}) |")
    factor = a["traffic"]["growth_factor"]
    lines += [
        "",
        f"## Sensitivity: traffic × {factor:g}",
        "",
        "| Option | Total today | Total at growth | Change |",
        "|---|---:|---:|---:|",
    ]
    for o, g in zip(base, grown, strict=True):
        lines.append(f"| {o.label} | €{o.total:,.0f} | €{g.total:,.0f} | ×{g.total / o.total:.2f} |")
    lines += ["", "## Break-even volume (self-host vs each API)", ""]
    for key in ("small", "large"):
        api = a["api"][key]
        be = breakeven_requests_per_month(
            inputs, ApiPricing(api["input_per_million"], api["output_per_million"]), a["self_host"]["ops_overhead_per_month"]
        )
        text = f"{be:,.0f} requests/month" if be else "not reached below 1,000 req/s"
        lines.append(f"- vs {api['label']}: self-hosting becomes cheaper at about **{text}**")
    lines += [
        "",
        "## What this report does not include",
        "",
        "- Quality differences between options. Run the Module 4 eval suite on each before choosing on price.",
        "- Engineering time to build self-hosting, data-residency requirements, and API rate limits (lesson 3.3).",
        "- Autoscaling lag: the autoscaled figure assumes capacity follows load perfectly, so it is a lower bound.",
        "",
    ]
    return "\n".join(lines)
